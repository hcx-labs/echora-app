"""Navidrome plugin settings as response bodies."""

from __future__ import annotations

import uuid

from backend.api.responses import ResponseModel
from backend.api.v1.auth._models import IsoDatetime


class PluginKey(ResponseModel):
    """An API key (its prefix only) and its state: active, expired or revoked."""

    id: uuid.UUID
    label: str
    prefix: str
    connection_id: uuid.UUID | None
    created_at: IsoDatetime
    expires_at: IsoDatetime
    revoked_at: IsoDatetime | None
    last_used_at: IsoDatetime | None
    status: str


class GeneratedKey(ResponseModel):
    """A new key; ``secret`` is shown only this once."""

    id: str
    label: str
    secret: str
    expires_at: IsoDatetime


class PluginSettingsView(ResponseModel):
    """The ranking profile, the integration's state and its keys."""

    musical_weight: int
    musical_semantic_weight: int
    missing_lyrics: str
    max_per_artist: int
    serve_lyrics: bool
    include_translations: bool
    lyrics_format: str
    key_expiry_days: int
    enabled: bool
    connection_id: uuid.UUID | None
    lyrics_paused: bool
    """Lyrics are withheld while a sync or lyrics job of the connection runs."""
    keys: list[PluginKey]


class PluginSaved(ResponseModel):
    """Whether the integration is on, and a key generated by enabling it (if any)."""

    enabled: bool
    generated_key: GeneratedKey | None
