#!/usr/bin/env python3
"""Print the settings catalog: every environment variable, its default and its meaning.

Reads no environment. Run with the packages importable, for example:
python scripts/export-runtime-settings.py [--ui]   (with core, worker and backend installed)
"""

import importlib

from backend.config import CONFIG_MODULES
from core.config import EchoraConfig, config_classes


def catalog() -> list[type[EchoraConfig]]:
    """Every config class of the modules above (and none a test defines), in that order."""
    for module in CONFIG_MODULES:
        importlib.import_module(module)
    classes = [cls for cls in config_classes() if cls.__module__ in CONFIG_MODULES]
    return sorted(classes, key=lambda cls: CONFIG_MODULES.index(cls.__module__))


def _value(value: object) -> str:
    if value is None:
        return ""
    if isinstance(value, bool):
        return str(value).lower()
    return str(value)


def template() -> str:
    """The commented catalog in configs/runtime.env.example."""
    lines = [
        "# Generated by scripts/export-runtime-settings.py. Do not edit defaults here.",
        "# Copy selected lines into .env and remove the leading comment marker.",
        "# All entries are commented so this catalog does not replace Compose defaults.",
        "# Secret values are blank. See docs/runtime-settings.md for deployment details.",
    ]
    for cls in catalog():
        lines += ["", f"# --- {cls.__name__}: {(cls.__doc__ or '').strip().splitlines()[0]}"]
        for entry in cls.entries():
            if entry.description:
                lines.append(f"#   {entry.description}")
            if entry.deprecated_names:
                lines.append(f"#   Also read as {', '.join(entry.deprecated_names)} (deprecated).")
            lines.append(f"# {entry.name}={'' if entry.secret else _value(entry.default)}")
    return "\n".join(lines) + "\n"


def ui_defaults() -> dict[str, int]:
    """The browser's defaults in web/components/runtime/runtimeConfig.defaults.json."""
    from backend.config import UiConfig

    return UiConfig.model_construct().public_ui()


if __name__ == "__main__":
    import json
    import sys

    if "--ui" in sys.argv:
        print(json.dumps(ui_defaults(), indent=2))
    else:
        print(template(), end="")
